"use client";

import React, { useState } from "react";
import { useDeals } from "@/hooks/useDeals";
import { DealCard } from "@/components/dealdesk/DealCard";
import { AddDealModal } from "@/components/dealdesk/AddDealModal";
import { PipelineStage, DealCardData } from "@/types/deal";
import { useAppStore } from "@/lib/store";
import {
  Download,
  Plus,
  Search,
  Sparkles,
  Trash2,
  ArrowUpDown,
  RefreshCw,
  Zap,
} from "lucide-react";

const COLUMNS: { id: PipelineStage; label: string; badgeColor: string }[] = [
  { id: "Discovered", label: "Discovered", badgeColor: "text-inkMuted dark:text-darkMuted" },
  { id: "Vetted", label: "Vetted", badgeColor: "text-cyan" },
  { id: "Pitch Ready", label: "Pitch Ready", badgeColor: "text-terracotta" },
  { id: "Dispatched", label: "Dispatched", badgeColor: "text-purple-600 dark:text-purple-400" },
];

export const KanbanBoard: React.FC = () => {
  const {
    deals,
    metrics,
    updateStage,
    createDeal,
    deleteDeal,
    clearDeals,
    loadPresetSeeds,
    isCreating,
    isSeeding,
  } = useDeals();

  const { showToast, activeProfile, mode, setActiveView } = useAppStore();

  const [filterDomain, setFilterDomain] = useState<string>("all");
  const [searchQuery, setSearchQuery] = useState<string>("");
  const [sortBy, setSortBy] = useState<"default" | "affinity" | "gmv" | "brand">("default");
  const [draggedCardId, setDraggedCardId] = useState<string | null>(null);

  // Add Deal Modal State
  const [isAddModalOpen, setIsAddModalOpen] = useState(false);
  const [addModalStage, setAddModalStage] = useState<PipelineStage>("Discovered");

  const handleOpenAddModal = (stage: PipelineStage = "Discovered") => {
    setAddModalStage(stage);
    setIsAddModalOpen(true);
  };

  const handleExportDossier = () => {
    if (deals.length === 0) {
      showToast("Cannot export empty dossier. Add deals or run Council first.");
      return;
    }

    const md = `# ${activeProfile.name} — Qloo Cultural Collaboration Dossier
Generated by Venture Pulse Autonomous Deal Desk Engine.
Grounded in Qloo's 250M+ Entity Cultural Taste Graph.
Pipeline Value: $${metrics.total_pipeline_value.toLocaleString()} | Avg Affinity: ${metrics.average_affinity.toFixed(1)}x

## Creator Aesthetic DNA
- Mode: ${mode === "creator" ? "Creator Profile" : "Brand Profile"}
- Category: ${activeProfile.category}
- Budget Tier: ${activeProfile.tier}
- Declared Anchors: ${activeProfile.chips.map((c) => `${c.name} (${c.weight}w)`).join(", ")}

## Live Partnership Deals in CRM Pipeline
${deals
  .map(
    (d, i) => `### ${i + 1}. ${d.brand_name} (⚡ ${d.affinity_multiplier} Affinity)
- Concept: ${d.title || d.spec?.title || `${d.brand_name} Limited Capsule`}
- Category: ${d.category}
- Stage: ${d.stage}
- MSRP: $${d.msrp || 185} USD
- Production Run: ${d.run_units || 500} units
- Projected GMV: $${(d.gmv || 0).toLocaleString()} USD
- Description: ${d.spec?.description || "Grounded Qloo cross-domain collaboration."}`
  )
  .join("\n\n")}
`;
    const blob = new Blob([md], { type: "text/markdown;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${activeProfile.name.toLowerCase().replace(/\s+/g, "_")}_campaign_dossier.md`;
    a.click();
    URL.revokeObjectURL(url);
    showToast(`↓ Exported Complete Campaign Dossier (${activeProfile.name})`);
  };

  // Filter & Search
  let processedDeals = deals.filter((d) => {
    const matchesDomain =
      filterDomain === "all" || d.category.toLowerCase() === filterDomain.toLowerCase();
    const matchesSearch =
      !searchQuery.trim() ||
      d.brand_name.toLowerCase().includes(searchQuery.toLowerCase()) ||
      (d.title && d.title.toLowerCase().includes(searchQuery.toLowerCase()));
    return matchesDomain && matchesSearch;
  });

  // Sorting
  if (sortBy === "affinity") {
    processedDeals.sort((a, b) => {
      const affA = parseFloat(a.affinity_multiplier.replace("x", "") || "0");
      const affB = parseFloat(b.affinity_multiplier.replace("x", "") || "0");
      return affB - affA;
    });
  } else if (sortBy === "gmv") {
    processedDeals.sort((a, b) => (b.gmv || 0) - (a.gmv || 0));
  } else if (sortBy === "brand") {
    processedDeals.sort((a, b) => a.brand_name.localeCompare(b.brand_name));
  }

  const handleDragStart = (e: React.DragEvent, cardId: string) => {
    setDraggedCardId(cardId);
    e.dataTransfer.setData("text/plain", cardId);
  };

  const handleDragOver = (e: React.DragEvent) => {
    e.preventDefault();
  };

  const handleDrop = (e: React.DragEvent, targetStage: PipelineStage) => {
    e.preventDefault();
    const cardId = draggedCardId || e.dataTransfer.getData("text/plain");
    if (!cardId) return;

    updateStage({ card_id: cardId, new_stage: targetStage });
    setDraggedCardId(null);
  };

  const handleMoveStage = (cardId: string, nextStage: PipelineStage) => {
    updateStage({ card_id: cardId, new_stage: nextStage });
  };

  const handleDeleteDeal = (cardId: string) => {
    deleteDeal(cardId);
  };

  const domains = ["all", "apparel", "tech", "beverage", "living", "accessories"];

  return (
    <div className="space-y-6">
      {/* CRM Header & Live Financial Metrics */}
      <div className="flex flex-col lg:flex-row lg:items-center justify-between gap-4 border-b border-editorial pb-5">
        <div>
          <div className="flex items-center space-x-2 text-xs font-mono uppercase tracking-widest text-terracotta font-semibold">
            <span>FIG 3.1 // PIPELINE INTELLIGENCE</span>
          </div>
          <h2 className="font-serif italic text-3xl sm:text-4xl text-ink dark:text-darkInk mt-0.5">
            Brand Partnership &amp; Drop Deal Desk
          </h2>
        </div>

        {/* Metric Summary Chips */}
        <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 text-xs font-mono">
          <div className="bg-surface dark:bg-darkSurface border border-editorial p-2.5 rounded">
            <span className="text-inkMuted dark:text-darkMuted block text-[10px]">
              PIPELINE VALUE
            </span>
            <span className="font-serif italic text-lg text-emerald font-bold">
              ${metrics.total_pipeline_value.toLocaleString()}
            </span>
          </div>
          <div className="bg-surface dark:bg-darkSurface border border-editorial p-2.5 rounded">
            <span className="text-inkMuted dark:text-darkMuted block text-[10px]">
              AVG AFFINITY
            </span>
            <span className="font-serif italic text-lg text-terracotta font-bold">
              {metrics.average_affinity.toFixed(1)}x
            </span>
          </div>
          <div className="bg-surface dark:bg-darkSurface border border-editorial p-2.5 rounded">
            <span className="text-inkMuted dark:text-darkMuted block text-[10px]">
              ACTIVE DEALS
            </span>
            <span className="font-serif italic text-lg text-ink dark:text-darkInk font-bold">
              {metrics.total_deals}
            </span>
          </div>
          <div className="bg-surface dark:bg-darkSurface border border-editorial p-2.5 rounded">
            <span className="text-inkMuted dark:text-darkMuted block text-[10px]">
              DISPATCHED
            </span>
            <span className="font-serif italic text-lg text-purple-600 dark:text-purple-400 font-bold">
              {deals.filter((d) => d.stage === "Dispatched").length} Synced
            </span>
          </div>
        </div>
      </div>

      {/* Filter, Search & Sort Toolbar */}
      <div className="flex flex-col md:flex-row items-stretch md:items-center justify-between gap-3 text-xs font-mono">
        {/* Left: Domain Pills & Search */}
        <div className="flex flex-wrap items-center gap-2">
          {/* Search Box */}
          <div className="relative">
            <Search className="w-3.5 h-3.5 absolute left-2.5 top-1/2 -translate-y-1/2 text-inkMuted dark:text-darkMuted" />
            <input
              type="text"
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              placeholder="Search deals..."
              className="pl-8 pr-2.5 py-1 rounded bg-surface dark:bg-darkSurface border border-editorial text-xs text-ink dark:text-darkInk focus:outline-none focus:border-terracotta w-36 sm:w-44"
            />
          </div>

          {/* Domain Pills */}
          <div className="flex items-center space-x-1 flex-wrap gap-y-1">
            {domains.map((dom) => (
              <button
                key={dom}
                onClick={() => setFilterDomain(dom)}
                className={`px-2.5 py-1 rounded capitalize font-medium transition ${
                  filterDomain === dom
                    ? "bg-ink text-surface dark:bg-surface dark:text-ink font-bold"
                    : "border border-editorial bg-surface dark:bg-darkSurface hover:bg-subtle dark:hover:bg-darkSubtle text-ink dark:text-darkInk"
                }`}
              >
                {dom}
              </button>
            ))}
          </div>
        </div>

        {/* Right: Sort & Global Actions */}
        <div className="flex flex-wrap items-center gap-2 justify-end">
          {/* Sort Dropdown */}
          <div className="flex items-center space-x-1 border border-editorial rounded bg-surface dark:bg-darkSurface px-2 py-1">
            <ArrowUpDown className="w-3 h-3 text-inkMuted dark:text-darkMuted" />
            <select
              value={sortBy}
              onChange={(e) => setSortBy(e.target.value as any)}
              className="bg-transparent text-ink dark:text-darkInk focus:outline-none text-xs font-mono"
            >
              <option value="default">Default Sort</option>
              <option value="affinity">Highest Affinity</option>
              <option value="gmv">Highest GMV</option>
              <option value="brand">Brand (A-Z)</option>
            </select>
          </div>

          {/* Add Custom Deal Button */}
          <button
            onClick={() => handleOpenAddModal("Discovered")}
            className="px-3 py-1.5 rounded bg-terracotta text-white font-mono text-xs font-bold hover:bg-terracotta/90 transition shadow flex items-center space-x-1"
            title="Create a new custom brand collaboration deal"
          >
            <Plus className="w-3.5 h-3.5" />
            <span>Add Deal</span>
          </button>

          {/* Clear Deals Button (if deals exist) */}
          {deals.length > 0 && (
            <button
              onClick={() => {
                if (confirm(`Are you sure you want to clear all ${deals.length} deals in this pipeline?`)) {
                  clearDeals();
                }
              }}
              className="px-2.5 py-1.5 rounded border border-editorial hover:border-red-500 hover:text-red-500 text-inkMuted dark:text-darkMuted transition text-xs font-mono"
              title="Clear all pipeline deals"
            >
              <Trash2 className="w-3.5 h-3.5" />
            </button>
          )}

          {/* Export Dossier */}
          <button
            onClick={handleExportDossier}
            className="px-3 py-1.5 rounded bg-ink text-surface dark:bg-surface dark:text-ink font-mono text-xs font-bold hover:bg-terracotta dark:hover:bg-terracotta hover:text-white transition shadow flex items-center space-x-1.5"
            title="Export all pipeline deals to Markdown dossier"
          >
            <Download className="w-3.5 h-3.5 text-terracotta" />
            <span>Export (.md)</span>
          </button>
        </div>
      </div>

      {/* Global Empty State Banner (When 0 Deals in Pipeline) */}
      {deals.length === 0 && (
        <div className="bg-surface dark:bg-darkSurface border border-dashed border-editorial rounded-xl p-8 sm:p-12 text-center space-y-4 shadow-sm animate-fade-in">
          <div className="w-12 h-12 mx-auto rounded-full bg-terracotta/10 text-terracotta flex items-center justify-center border border-terracotta/20">
            <Sparkles className="w-6 h-6" />
          </div>
          <div className="max-w-md mx-auto space-y-1">
            <h3 className="font-serif italic text-2xl text-ink dark:text-darkInk">
              Deal Desk Pipeline is Empty
            </h3>
            <p className="text-xs font-mono text-inkMuted dark:text-darkMuted leading-relaxed">
              No brand deals found for <strong>{activeProfile.name}</strong>. Run the adversarial
              LangGraph council to discover verified drops, add custom targets, or load curated
              archetype seeds.
            </p>
          </div>
          <div className="pt-2 flex flex-wrap items-center justify-center gap-3 font-mono text-xs">
            <button
              onClick={() => setActiveView("debate")}
              className="px-4 py-2 rounded bg-ink text-surface dark:bg-surface dark:text-ink font-bold hover:bg-terracotta dark:hover:bg-terracotta hover:text-white transition shadow flex items-center space-x-1.5"
            >
              <Zap className="w-3.5 h-3.5 text-terracotta" />
              <span>Launch LangGraph Council</span>
            </button>
            <button
              onClick={() => handleOpenAddModal("Discovered")}
              className="px-4 py-2 rounded bg-terracotta text-white font-bold hover:bg-terracotta/90 transition shadow flex items-center space-x-1.5"
            >
              <Plus className="w-3.5 h-3.5" />
              <span>Add Custom Deal</span>
            </button>
            <button
              disabled={isSeeding}
              onClick={() => loadPresetSeeds()}
              className="px-4 py-2 rounded border border-editorial hover:border-ink dark:hover:border-white text-ink dark:text-darkInk transition flex items-center space-x-1.5 disabled:opacity-50"
            >
              <RefreshCw className={`w-3.5 h-3.5 ${isSeeding ? "animate-spin" : ""}`} />
              <span>Load Archetype Seeds</span>
            </button>
          </div>
        </div>
      )}

      {/* 4-Column Kanban Grid */}
      <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-4">
        {COLUMNS.map((col) => {
          const colDeals = processedDeals.filter((d) => d.stage === col.id);

          return (
            <div
              key={col.id}
              onDragOver={handleDragOver}
              onDrop={(e) => handleDrop(e, col.id)}
              className="bg-subtle/50 dark:bg-darkSubtle/50 border border-editorial rounded-lg p-3 space-y-3 min-h-[460px] flex flex-col justify-between"
            >
              <div className="space-y-3">
                {/* Column Header */}
                <div className="flex items-center justify-between pb-2 border-b border-editorial text-xs font-mono">
                  <div className="flex items-center space-x-2">
                    <span className="font-bold text-ink dark:text-darkInk uppercase tracking-wider">
                      {col.label}
                    </span>
                    <span
                      className={`px-2 py-0.5 rounded bg-surface dark:bg-darkSurface border border-editorial font-bold ${col.badgeColor}`}
                    >
                      {colDeals.length}
                    </span>
                  </div>
                  {/* Quick Add Button on Column Header */}
                  <button
                    onClick={() => handleOpenAddModal(col.id)}
                    className="w-5 h-5 rounded flex items-center justify-center text-inkMuted dark:text-darkMuted hover:text-terracotta hover:bg-surface dark:hover:bg-darkSurface transition border border-transparent hover:border-editorial"
                    title={`Add new deal directly to ${col.label}`}
                  >
                    <Plus className="w-3 h-3" />
                  </button>
                </div>

                {/* Column Cards */}
                <div className="space-y-3">
                  {colDeals.map((deal) => (
                    <DealCard
                      key={deal.card_id}
                      deal={deal}
                      onMoveStage={handleMoveStage}
                      onDelete={handleDeleteDeal}
                      onDragStart={handleDragStart}
                    />
                  ))}

                  {/* Column Empty State */}
                  {colDeals.length === 0 && (
                    <div className="h-32 border border-dashed border-editorial rounded-lg flex flex-col items-center justify-center text-inkMuted dark:text-darkMuted text-xs font-mono p-3 space-y-2 text-center">
                      <span className="text-[11px]">No deals in {col.label}</span>
                      <button
                        onClick={() => handleOpenAddModal(col.id)}
                        className="text-[10px] text-terracotta hover:underline font-bold flex items-center space-x-1"
                      >
                        <Plus className="w-3 h-3 inline" />
                        <span>Add Deal</span>
                      </button>
                    </div>
                  )}
                </div>
              </div>

              {/* Column Footer */}
              <div className="pt-2 border-t border-editorial text-[10px] font-mono text-inkMuted dark:text-darkMuted flex items-center justify-between">
                <span>Stage {COLUMNS.indexOf(col) + 1}/4</span>
                <span>{col.id === "Dispatched" ? "Live CRM Sync" : "Drag / Move Active"}</span>
              </div>
            </div>
          );
        })}
      </div>

      {/* Add Deal Modal */}
      <AddDealModal
        isOpen={isAddModalOpen}
        initialStage={addModalStage}
        onClose={() => setIsAddModalOpen(false)}
        onSubmit={(newDeal) => createDeal(newDeal)}
      />
    </div>
  );
};
